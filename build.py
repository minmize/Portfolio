#!/usr/bin/env python3
"""
Bundle the site into ONE self-contained index.html.

Edit files in src/ (data.js for content, app.js / styles.css for behaviour and looks),
then run:

    python3 build.py

Every local <link rel="stylesheet"> and <script src> in src/index.html is inlined, including
three.js from src/vendor/, so the generated index.html works anywhere — opened as a file, in an
editor preview, or on GitHub Pages — with no other files next to it.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"


def read(rel):
    return (SRC / rel).read_text(encoding="utf-8")


def inline_css(m):
    href = m.group(1)
    if href.startswith(("http:", "https:", "//")):
        return m.group(0)
    return "<style>\n" + read(href) + "\n</style>"


def inline_js(m):
    src = m.group(1)
    if src.startswith(("http:", "https:", "//")):
        return m.group(0)
    code = read(src).replace("</script", "<\\/script")
    return "<script>/* " + src + " */\n" + code + "\n</script>"


def main():
    html = read("index.html")
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)"\s*/?>', inline_css, html)
    html = re.sub(r'<script src="([^"]+)"></script>', inline_js, html)
    banner = "<!-- GENERATED by build.py from src/ — edit src/ and run `python3 build.py`. -->\n"
    html = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + banner, 1)
    out = ROOT / "index.html"
    out.write_text(html, encoding="utf-8")
    print("Wrote %s (%.0f KB)" % (out.name, out.stat().st_size / 1024))


if __name__ == "__main__":
    main()
